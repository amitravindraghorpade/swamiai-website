#!/usr/bin/env python3
"""Build /mr/index.html and /hi/index.html from index.html + i18n.js.

Google does not see text that JavaScript swaps in after a button click, so the
Marathi and Hindi versions get their own pre-translated pages and URLs.

Run after every change to index.html or i18n.js:
    python3 tools/build-languages.py
Needs: python3 with beautifulsoup4, and node (to read i18n.js).
"""
import json, os, re, subprocess
from bs4 import BeautifulSoup

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://swamiai.in"

META = {
    "mr": {
        "title": "स्मार्ट सिटीसाठी AI CCTV विश्लेषण | स्वामी इंटेलिजंट सिस्टिम्स",
        "desc": "तुमच्या सध्याच्या CCTV कॅमेऱ्यांवर AI: खड्डे, कचरा टाकणे, पाणी साचणे, झाडे पडणे आणि अपघात ओळखतो आणि प्रत्येक प्रकरण बंद होईपर्यंत पाठपुरावा करतो. खारघर, नवी मुंबई.",
        "og": "CCTV कॅमेऱ्यांपासून नागरी बुद्धिमत्तेपर्यंत. शहरांकडे आधीच असलेल्या कॅमेऱ्यांवर स्मार्ट गव्हर्नन्ससाठी AI व्हिडिओ विश्लेषण.",
        "locale": "mr_IN",
    },
    "hi": {
        "title": "स्मार्ट सिटी के लिए AI CCTV एनालिटिक्स | स्वामी इंटेलिजेंट सिस्टम्स",
        "desc": "आपके मौजूदा CCTV कैमरों पर AI: गड्ढे, कचरा फेंकना, जलभराव, गिरे पेड़ और दुर्घटनाएँ पहचानता है और हर मामले को बंद होने तक ट्रैक करता है। खारघर, नवी मुंबई।",
        "og": "CCTV कैमरों से नागरिक इंटेलिजेंस तक। शहरों के पास पहले से मौजूद कैमरों पर स्मार्ट गवर्नेंस के लिए AI वीडियो एनालिटिक्स।",
        "locale": "hi_IN",
    },
}


def load_i18n():
    js = "global.window={};require(process.argv[1]);process.stdout.write(JSON.stringify(window.I18N))"
    out = subprocess.check_output(["node", "-e", js, os.path.join(ROOT, "i18n.js")])
    return json.loads(out)


def build(lang, dict_, src):
    soup = BeautifulSoup(src, "html.parser")
    m = META[lang]
    soup.html["lang"] = lang

    # translated text
    for el in soup.select("[data-i18n]"):
        k = el["data-i18n"]
        if k in dict_:
            el.clear()
            el.append(BeautifulSoup(dict_[k], "html.parser"))

    # head
    soup.title.string = m["title"]
    soup.find("meta", attrs={"name": "description"})["content"] = m["desc"]
    soup.find("link", rel="canonical")["href"] = f"{SITE}/{lang}/"
    for prop, val in (("og:title", m["title"]), ("og:description", m["og"]),
                      ("og:url", f"{SITE}/{lang}/"), ("og:locale", m["locale"])):
        tag = soup.find("meta", property=prop)
        if tag:
            tag["content"] = val

    # FAQ structured data in this language
    faq = soup.find("script", id="ld-faq")
    if faq:
        data = json.loads(faq.string)
        data["inLanguage"] = lang
        for i, q in enumerate(data["mainEntity"], 1):
            q["name"] = BeautifulSoup(dict_.get(f"q.{i}", q["name"]), "html.parser").get_text()
            q["acceptedAnswer"]["text"] = BeautifulSoup(
                dict_.get(f"a.{i}", q["acceptedAnswer"]["text"]), "html.parser").get_text()
        faq.string = "\n" + json.dumps(data, ensure_ascii=False) + "\n"

    # relative asset paths move one folder up
    for tag in soup.find_all(True):
        for attr in ("src", "href", "poster", "data-src"):
            v = tag.get(attr)
            if v and not re.match(r"^(https?:|mailto:|tel:|#|/|data:)", v):
                tag[attr] = "../" + v

    out = str(soup)
    if not out.lstrip().lower().startswith("<!doctype"):
        out = "<!doctype html>\n" + out
    note = "<!-- GENERATED by tools/build-languages.py from index.html + i18n.js. Do not edit by hand. -->\n"
    out = out.replace("<head>", "<head>\n" + note, 1)
    os.makedirs(os.path.join(ROOT, lang), exist_ok=True)
    with open(os.path.join(ROOT, lang, "index.html"), "w", encoding="utf-8") as f:
        f.write(out)
    missing = [el["data-i18n"] for el in soup.select("[data-i18n]") if el["data-i18n"] not in dict_]
    print(f"{lang}/index.html written" + (f" ({len(missing)} keys untranslated: {missing[:5]})" if missing else ""))


def main():
    with open(os.path.join(ROOT, "index.html"), encoding="utf-8") as f:
        src = f.read()
    i18n = load_i18n()
    for lang in META:
        build(lang, i18n[lang], src)


if __name__ == "__main__":
    main()
